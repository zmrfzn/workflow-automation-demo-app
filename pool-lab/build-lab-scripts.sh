#!/usr/bin/env bash
# ─────────────────────────────────────────────
# Builds self-contained Instruqt track scripts from lib/ + lab/:
#   <out>/setup-<vm>    = lib/common.sh + lib/claim.sh + lab/bootstrap.sh
#   <out>/cleanup-<vm>  = lib/common.sh + lib/claim.sh + lab/teardown.sh
# Every line carrying the inline marker (the lib `source` lines) and every extra shebang is removed,
# so the output depends on no other file at runtime. Each output is syntax-checked with bash -n.
#
# Usage: ./build-lab-scripts.sh [--vm <name>] [--out <dir>]   (defaults: --vm lab, --out <this dir>/dist)
# Copy the outputs into the track's track_scripts/ dir (see instruqt/config.snippet.yml).
# ─────────────────────────────────────────────
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
VM="lab"
OUT="$HERE/dist"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --vm)  VM="${2:?--vm needs a value}"; shift 2 ;;
    --out) OUT="${2:?--out needs a value}"; shift 2 ;;
    -h|--help) sed -n '2,10p' "${BASH_SOURCE[0]}"; exit 0 ;;
    *) echo "Unknown argument: $1" >&2; exit 2 ;;
  esac
done

MARKER='# pool-lab:inline'
mkdir -p "$OUT"

# build <output name> <body script>
build() {
  local name="$1" body="$2" target="$OUT/$1" f
  {
    echo '#!/usr/bin/env bash'
    echo "# GENERATED by pool-lab/build-lab-scripts.sh from lib/common.sh, lib/claim.sh and lab/${body}. Do not edit."
    for f in "$HERE/lib/common.sh" "$HERE/lib/claim.sh" "$HERE/lab/$body"; do
      echo ""
      sed -e "/${MARKER}/d" -e '/^#!/d' "$f"
    done
  } > "$target"
  chmod +x "$target"
  bash -n "$target" || { echo "ERROR: syntax check failed for $target" >&2; exit 1; }
  if grep -q "$MARKER" "$target"; then
    echo "ERROR: inline marker left in $target" >&2; exit 1
  fi
  echo "built $target"
}

build "setup-${VM}" bootstrap.sh
build "cleanup-${VM}" teardown.sh
